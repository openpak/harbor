bool Install(const std::filesystem::path& load_dir) {
    const auto path = load_dir / "010000000000000C" / "openpak_bcat_key" / "exefs" / PatchName;
    const std::string want{reinterpret_cast<const char*>(Ips), sizeof(Ips)};
    if (Platform::ReadFile(path) == want) {
        return true;
    }
    if (!Platform::CreateParentDirs(path) || !Platform::WriteAtomically(path, want)) {
        LOG_WARNING(Service, "bcat: could not install the OpenPak key patch at {}", path.string());
        return false;
    }
    LOG_INFO(Service, "bcat: installed the OpenPak key patch at {}", path.string());
    return true;
}

