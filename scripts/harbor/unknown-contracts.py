"""List every unknown-contract site in Harbor's source for docs/harbor/unknown-contracts.md.

    scripts/harbor/unknown-contracts.py [--ryujinx <ryujinx-android checkout>] [--write]

Finds LOG_UNKNOWN_CONTRACT(...) calls and log strings that start "unknown contract:" under src/,
and prints a Markdown table (area, file:line, the logged text, which carries what is answered and
why). With --ryujinx it also lists the Ryujinx Harbor's "Unknown contract:" sites and which of them
have no Eden-side site with the same interface and command. With --write it replaces the part of
docs/harbor/unknown-contracts.md between the generated markers instead of printing.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOC = ROOT / "docs/harbor/unknown-contracts.md"
START = "<!-- generated:start -->"
END = "<!-- generated:end -->"

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def statement_at(text, start):
    """The source of the call starting at `start`, up to its closing parenthesis."""
    depth = 0
    i = text.index("(", start)
    j = i
    in_string = False
    while j < len(text):
        c = text[j]
        if in_string:
            if c == "\\":
                j += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return text[start : j + 1]
        j += 1
    return text[start:]


def message_of(call):
    """The adjacent string literals of a log call, joined; '{}' marks a runtime value."""
    parts = STRING.findall(call)
    joined = "".join(parts).replace("\\n", " ")
    return re.sub(r"\s+", " ", joined).strip()


def eden_sites():
    sites = []
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix not in (".cpp", ".h") or "selfcheck" in path.name:
            continue
        text = path.read_text(errors="replace")
        lowered = text.lower()
        if "unknown contract" not in lowered and "unknown_contract" not in lowered:
            continue
        for m in re.finditer(r"LOG_UNKNOWN_CONTRACT\s*\(|LOG_(?:WARNING|INFO|ERROR|DEBUG)\s*\(", text):
            if text[max(0, m.start() - 9) : m.start()].endswith("#define "):
                continue
            call = statement_at(text, m.start())
            msg = message_of(call)
            if not m.group(0).startswith("LOG_UNKNOWN_CONTRACT"):
                if not msg.lower().startswith("unknown contract:"):
                    continue
                msg = msg[len("unknown contract:") :].strip()
            if not msg:
                continue
            line = text.count("\n", 0, m.start()) + 1
            rel = path.relative_to(ROOT).as_posix()
            area = rel.split("/")[4] if rel.startswith("src/core/hle/service/") else rel.split("/")[1]
            sites.append((area, rel, line, msg))
    return sites


def ryujinx_sites(checkout):
    sites = []
    src = pathlib.Path(checkout) / "src"
    for path in sorted(src.rglob("*.cs")):
        if "Tests" in path.parts:
            continue
        text = path.read_text(errors="replace")
        for m in re.finditer(r'"Unknown contract: ([^"]*)"', text):
            line = text.count("\n", 0, m.start()) + 1
            msg = re.sub(r"\{[^}]*\}", "{}", m.group(1))
            sites.append((path.relative_to(src).as_posix(), line, msg))
    return sites


KEY = re.compile(r"\b(I[A-Z]\w+|[a-z]+:[a-z0-9]+|acc|am|ns|news|sfdnsres|audctl|pctl|olsc)\b(?:\([^)]*\))? (\d+)\b")


def key_of(msg):
    m = KEY.search(msg)
    if m:
        return (m.group(1).lower(), m.group(2))
    # No command number: the service and the command's name ("set:sys SetLanguageCode(...").
    words = re.findall(r"[A-Za-z:]+", msg)
    return tuple(w.lower() for w in words[:2]) if len(words) >= 2 else None


def escape(text):
    return text.replace("|", "\\|")


def render(eden, ryujinx):
    out = [f"{len(eden)} Eden-side sites (generated by scripts/harbor/unknown-contracts.py).", ""]
    out += ["| Area | Site | What is logged (answer and reason) |", "|---|---|---|"]
    for area, rel, line, msg in eden:
        out.append(f"| {area} | `{rel}:{line}` | {escape(msg)} |")
    if ryujinx is not None:
        eden_keys = {key_of(m) for *_, m in eden} - {None}
        missing = [(p, l, m) for p, l, m in ryujinx if key_of(m) not in eden_keys]
        out += ["", f"{len(ryujinx)} Ryujinx Harbor sites; {len(missing)} have no Eden-side site "
                "with the same interface and command (see the notes above for each):", ""]
        out += ["| Ryujinx site | Logged there |", "|---|---|"]
        for p, l, m in missing:
            out.append(f"| `{p}:{l}` | {escape(m)} |")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ryujinx")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    body = render(eden_sites(), ryujinx_sites(args.ryujinx) if args.ryujinx else None)
    if not args.write:
        print(body)
        return
    doc = DOC.read_text()
    if START not in doc or END not in doc:
        sys.exit(f"{DOC} has no generated markers")
    head, rest = doc.split(START, 1)
    _, tail = rest.split(END, 1)
    DOC.write_text(f"{head}{START}\n{body}\n{END}{tail}")


if __name__ == "__main__":
    main()
