#include "core/hle/service/ldn/local_wireless_codec.h"
#include "core/hle/service/ldn/local_wireless_transport.h"
#include <boost/asio.hpp>
#include <chrono>
#include <condition_variable>
#include <deque>
#include <iostream>
#include <mutex>
#include <stdexcept>
#include <thread>
#include <utility>

using namespace Service::LDN;
namespace Codec = Service::LDN::LocalWirelessCodec;
namespace asio = boost::asio;
using Tcp = asio::ip::tcp;
using Udp = asio::ip::udp;
using Error = boost::system::error_code;
using namespace std::chrono_literals;

void Check(bool condition, const char *message) {
  if (!condition)
    throw std::runtime_error(message);
}

struct Inbox {
  std::mutex mutex;
  std::condition_variable changed;
  std::deque<LocalWirelessPacket> packets;
  void Push(LocalWirelessPacket packet) {
    std::scoped_lock lock{mutex};
    packets.push_back(std::move(packet));
    changed.notify_all();
  }
  LocalWirelessPacket Take(LocalWirelessMessage type) {
    std::unique_lock lock{mutex};
    Check(changed.wait_for(lock, 3s, [&] { return !packets.empty(); }),
          "event timed out");
    auto packet = std::move(packets.front());
    packets.pop_front();
    Check(packet.type == type, "unexpected event");
    return packet;
  }
};

// Independent golden frames, not generated by Harbor's encoder. The compressed
// body is a zero byte followed by the number of *additional* zeros, up to 256
// per pair.
std::vector<std::uint8_t> Zeros(std::uint8_t opcode, std::size_t size) {
  std::vector<std::uint8_t> body;
  for (auto remaining = size; remaining;) {
    const auto run = std::min<std::size_t>(remaining, 256);
    body.push_back(0);
    body.push_back(static_cast<std::uint8_t>(run - 1));
    remaining -= run;
  }
  std::vector<std::uint8_t> frame{0,
                                  0x14,
                                  0x45,
                                  0x11,
                                  opcode,
                                  1,
                                  static_cast<std::uint8_t>(body.size()),
                                  0,
                                  static_cast<std::uint8_t>(size),
                                  static_cast<std::uint8_t>(size >> 8),
                                  0,
                                  0};
  frame.insert(frame.end(), body.begin(), body.end());
  return frame;
}

std::vector<std::uint8_t> Read(Tcp::socket &socket, std::size_t size) {
  socket.non_blocking(true);
  std::vector<std::uint8_t> bytes(size);
  std::size_t offset = 0;
  const auto deadline = std::chrono::steady_clock::now() + 3s;
  while (offset < size) {
    Error ec;
    const auto count = socket.read_some(
        asio::buffer(bytes.data() + offset, size - offset), ec);
    if (ec == asio::error::would_block || ec == asio::error::try_again) {
      Check(std::chrono::steady_clock::now() < deadline,
            "socket read timed out");
      std::this_thread::sleep_for(1ms);
      continue;
    }
    Check(!ec, "socket read failed");
    offset += count;
  }
  socket.non_blocking(false);
  return bytes;
}

void Closed(Tcp::socket &socket) {
  socket.non_blocking(true);
  const auto deadline = std::chrono::steady_clock::now() + 3s;
  for (;;) {
    std::array<char, 1> byte;
    Error ec;
    socket.read_some(asio::buffer(byte), ec);
    if (ec == asio::error::eof || ec == asio::error::connection_reset)
      return;
    Check(ec == asio::error::would_block || ec == asio::error::try_again,
          "expected closed socket");
    Check(std::chrono::steady_clock::now() < deadline, "close timed out");
    std::this_thread::sleep_for(1ms);
  }
}

int main() try {
  const std::vector<std::uint8_t> scan{0, 0x14, 0x45, 0x11, 0, 0,
                                       0, 0,    0,    0,    0, 0};
  Check(Codec::Encode(0, {}) == scan, "scan wire header mismatch");
  auto compressed = Zeros(3, 0x480);
  Check(Codec::Decode(compressed) == std::vector<std::uint8_t>(0x480),
        "zero-run decoding");
  auto invalid = compressed;
  invalid[8] = 1;
  Check(!Codec::Decode(invalid), "accepted decompression overflow");
  invalid = {0, 0x14, 0x45, 0x11, 2, 1, 1, 0, 1, 0, 0, 0, 0};
  Check(!Codec::Decode(invalid), "accepted truncated run");
  invalid = scan;
  invalid[6] = 0xff;
  invalid[7] = 0xff;
  Check(!Codec::ValidHeader(invalid), "accepted oversized frame");
  invalid = scan;
  invalid[0] = 1;
  Check(!Codec::Decode(invalid), "accepted bad magic");
  invalid = scan;
  invalid.push_back(0);
  Check(!Codec::Decode(invalid), "accepted trailing datagram data");
  for (std::size_t i = 0; i < compressed.size(); ++i) {
    Check(!Codec::Decode(std::span{compressed}.first(i)),
          "accepted partial frame");
  }

  asio::io_context io;
  const auto own = asio::ip::make_address_v4("127.0.0.1");
  const auto other = asio::ip::make_address_v4("127.0.0.2");
  Inbox inbox;
  LocalWirelessTransport transport;
  std::string error;
  Check(transport.Start(
            own.to_bytes(), {255, 0, 0, 0},
            [&](auto packet) { inbox.Push(std::move(packet)); }, error),
        error.c_str());
  {
    Udp::socket peer{io, Udp::endpoint{other, 0}};
    auto reply = Zeros(1, 0x480);
    peer.send_to(asio::buffer(reply),
                 Udp::endpoint{own, LocalWirelessTransport::Port});
    const auto event = inbox.Take(LocalWirelessMessage::ScanResponse);
    Check(event.peer == other.to_bytes() && event.data.size() == 0x480,
          "UDP discovery");
  }
  transport.SetHosting(true);
  for (int attempt = 0; attempt < 2; ++attempt) {
    Tcp::socket peer{io};
    peer.open(Tcp::v4());
    peer.bind(Tcp::endpoint{other, 0});
    peer.connect(Tcp::endpoint{own, LocalWirelessTransport::Port});
    const auto connect = Zeros(2, 0x40);
    // A TCP header may arrive in pieces.
    asio::write(peer, asio::buffer(connect.data(), 3));
    asio::write(peer, asio::buffer(connect.data() + 3, connect.size() - 3));
    const auto event = inbox.Take(LocalWirelessMessage::Connect);
    Check(event.data.size() == 0x40 && event.data[0] == 2 &&
              event.data[3] == 127,
          "host did not use actual peer address");
    transport.Send({LocalWirelessMessage::Sync, other.to_bytes(),
                    std::vector<std::uint8_t>(0x480)});
    auto header = Read(peer, 12);
    Check(header[4] == 3 && Codec::Read16(header, 6) == 0x480,
          "host sync header");
    auto body = Read(peer, 0x480);
    Check(body == std::vector<std::uint8_t>(0x480), "host sync body");
    peer.close();
    Check(inbox.Take(LocalWirelessMessage::Disconnect).data == event.data,
          "disconnect identity");
  }
  {
    Tcp::socket peer{io};
    peer.open(Tcp::v4());
    peer.bind(Tcp::endpoint{other, 0});
    peer.connect(Tcp::endpoint{own, LocalWirelessTransport::Port});
    asio::write(peer, asio::buffer(invalid)); // invalid magic from earlier
    Closed(peer);
  }
  transport.SetHosting(false);
  {
    Tcp::acceptor host{io, Tcp::endpoint{other, LocalWirelessTransport::Port}};
    host.non_blocking(true);
    transport.Send({LocalWirelessMessage::Connect, other.to_bytes(),
                    std::vector<std::uint8_t>(0x40)});
    Tcp::socket peer{io};
    const auto deadline = std::chrono::steady_clock::now() + 3s;
    for (;;) {
      Error ec;
      host.accept(peer, ec);
      if (!ec)
        break;
      Check(ec == asio::error::would_block || ec == asio::error::try_again,
            "accept failed");
      Check(std::chrono::steady_clock::now() < deadline, "accept timed out");
      std::this_thread::sleep_for(1ms);
    }
    Check(Read(peer, 12)[4] == 2 && Read(peer, 0x40).size() == 0x40,
          "station connect frame");
    // Two coalesced frames must both be delivered without waiting for a third
    // read.
    auto updates = compressed;
    updates.insert(updates.end(), compressed.begin(), compressed.end());
    asio::write(peer, asio::buffer(updates));
    Check(inbox.Take(LocalWirelessMessage::Sync).data.size() == 0x480,
          "first sync");
    Check(inbox.Take(LocalWirelessMessage::Sync).data.size() == 0x480,
          "second sync");
    peer.close();
    inbox.Take(LocalWirelessMessage::Destroy);
  }
  // A refused connection must complete with failure rather than hanging or
  // reporting joined.
  transport.Send({LocalWirelessMessage::Connect, other.to_bytes(),
                  std::vector<std::uint8_t>(0x40)});
  inbox.Take(LocalWirelessMessage::Destroy);
  // A conflicting listener must fail without breaking the active transport.
  {
    LocalWirelessTransport collision;
    std::string conflict;
    Check(!collision.Start(
              own.to_bytes(), {255, 0, 0, 0}, [](auto) {}, conflict),
          "duplicate port initialization succeeded");
    Check(!conflict.empty(), "missing port conflict diagnostic");
  }
  transport.SetHosting(true);
  {
    Tcp::socket peer{io};
    peer.open(Tcp::v4());
    peer.bind(Tcp::endpoint{other, 0});
    peer.connect(Tcp::endpoint{own, LocalWirelessTransport::Port});
    auto connect = Zeros(2, 0x40);
    asio::write(peer, asio::buffer(connect));
    inbox.Take(LocalWirelessMessage::Connect);
    transport.Stop();
    Closed(peer);
  }
  // Stop releases both ports before the old object is destroyed.
  {
    LocalWirelessTransport next;
    std::string next_error;
    Check(next.Start(
              own.to_bytes(), {255, 0, 0, 0}, [](auto) {}, next_error),
          next_error.c_str());
    next.Stop();
  }
  std::cout << "local wireless codec, UDP discovery, host/rejoin, "
               "fragmented/coalesced TCP, EOF and refusal passed\n";
  return 0;
} catch (const std::exception &error) {
  std::cerr << error.what() << '\n';
  return 1;
}
